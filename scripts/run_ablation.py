"""Run Stage A only, plain LLM, and RAG LLM on the same split."""

from __future__ import annotations

import argparse
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from backend.evaluation.evaluate_end_to_end import evaluate
from backend.stage_a.pipeline import run_stage_a_batch
from backend.stage_b.stage_b import run_stage_b_batch


def _load_records(path: Path) -> list[dict]:
    records = json.loads(path.read_text(encoding="utf-8"))
    return records if isinstance(records, list) else [records]


def _split(records: list[dict], seed: int = 355) -> dict:
    buckets = defaultdict(list)
    for rec in records:
        label = rec.get("ground_truth_label", {})
        key = label.get("error_type") if label.get("is_error") else "clean"
        buckets[key].append(str(rec.get("transcript_id")))
    rng = random.Random(seed)
    dev, test = [], []
    for ids in buckets.values():
        rng.shuffle(ids)
        n_dev = max(1, round(len(ids) * 0.30))
        dev.extend(ids[:n_dev])
        test.extend(ids[n_dev:])
    return {"seed": seed, "dev": sorted(dev), "test": sorted(test)}


def _write_predictions(path: Path, records_by_mode: dict[str, list[dict]]):
    with path.open("w", encoding="utf-8") as f:
        for mode, records in records_by_mode.items():
            for rec in records:
                f.write(json.dumps({
                    "mode": mode,
                    "transcript_id": rec.get("transcript_id"),
                    "ground_truth_label": rec.get("ground_truth_label"),
                    "stage_b": rec.get("stage_b", {}),
                    "n_findings": len(rec.get("stage_b_findings", [])),
                    "findings": rec.get("stage_b_findings", []),
                }, separators=(",", ":")) + "\n")


def _md(metrics: dict) -> str:
    lines = ["# Ablation Metrics", "", "All numbers are generated by `scripts/run_ablation.py`.", ""]
    for scope, scoped in metrics.items():
        lines += [f"## {scope}", ""]
        for mode, data in scoped.items():
            if mode.startswith("paired_"):
                lines += [f"### {mode}", f"`{json.dumps(data)}`", ""]
                continue
            c = data["confusion"]
            lines += [
                f"### {mode}",
                f"- n: {data['n']}",
                f"- confusion: TP={c['tp']} FP={c['fp']} FN={c['fn']} TN={c['tn']}",
                f"- precision: {data['precision']:.3f}",
                f"- recall: {data['recall']:.3f}",
                f"- F1: {data['f1']:.3f}",
                f"- false-positive rate on clean records: {data['false_positive_rate_clean']:.3f}",
                f"- fallback rate: {data['fallback_rate']:.3f}",
                "",
            ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="dataset/processed/mtsamples_with_errors.json")
    parser.add_argument("--limit", type=int)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--max-calls", type=int)
    args = parser.parse_args()

    records = _load_records(ROOT / args.input)
    if args.limit:
        records = records[:args.limit]
    split = _split(records)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "split.json").write_text(json.dumps(split, indent=2), encoding="utf-8")

    stage_a = run_stage_a_batch(records)
    records_by_mode = {
        mode: run_stage_b_batch(stage_a, mode=mode, dry_run=args.dry_run, max_calls=args.max_calls, project_root=ROOT)
        for mode in ("stage_a_only", "llm_plain", "llm_rag")
    }

    metrics = {
        "test_headline_no_reference": evaluate(records_by_mode, set(split["test"])),
        "all_270_includes_dev": evaluate(records_by_mode, None),
    }

    (ROOT / "results" / "ablation_metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    (ROOT / "results" / "ablation_metrics.md").write_text(_md(metrics), encoding="utf-8")
    _write_predictions(ROOT / "results" / "ablation_predictions.jsonl", records_by_mode)
    print(json.dumps({
        "records": len(records),
        "dry_run": args.dry_run,
        "outputs": [
            "results/ablation_metrics.json",
            "results/ablation_metrics.md",
            "results/ablation_predictions.jsonl",
            "results/split.json",
        ],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
